// Generates supabase/seed.sql from src/data/seedItems.js.
// Upserts on slug, so re-running refreshes content without touching comments.
// Requires the `round` column (migration 0007).
import { writeFileSync } from 'node:fs'
import { SEED_ITEMS } from '../src/data/seedItems.js'

const lit = (v) => (v == null ? 'null' : `'${String(v).replace(/'/g, "''")}'`)

const rows = SEED_ITEMS.map((i) =>
  `  (${lit(i.slug)}, ${lit(i.type)}, ${lit(i.name)}, ${lit(i.description)}, ${lit(i.image_url)}, ${lit(JSON.stringify(i.data))}::jsonb, ${i.display_order}, ${i.round ?? 1})`,
).join(',\n')

const sql = `-- Generated by \`npm run seed:sql\` from src/data/seedItems.js — do not edit by hand.
insert into public.brand_items (slug, type, name, description, image_url, data, display_order, round)
values
${rows}
on conflict (slug) do update set
  type = excluded.type,
  name = excluded.name,
  description = excluded.description,
  image_url = coalesce(excluded.image_url, public.brand_items.image_url),
  data = excluded.data,
  display_order = excluded.display_order,
  round = excluded.round,
  updated_at = now();
`

writeFileSync(new URL('../supabase/seed.sql', import.meta.url), sql)
console.log(`Wrote supabase/seed.sql (${SEED_ITEMS.length} items)`)
